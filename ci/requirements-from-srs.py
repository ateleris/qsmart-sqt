"""Write ci/requirements.csv, the SRS requirement list CI checks the tests against.

The SRS lives in the private documentation repository, which CI cannot read.
CI needs only the requirement UIDs, titles and verification methods, plus the
release each requirement is planned for, so this script extracts those into a
file kept in this repository. Run it whenever the SRS or the release plan gets
a new issue, from a checkout of the documentation repository at a tag:

    git -C ../qsmart-sqt-documentation checkout <docs tag>
    python3 ci/requirements-from-srs.py \\
        --srs ../qsmart-sqt-documentation/deliverables/editable/SQT-SRS_Software_Requirements_Specification_SRS.sdoc \\
        --source "<docs tag> (<commit>)"

The release groups below mirror the release plan of SQT-TN-AP
(SQT-PL-0002-ATS); change them together with that plan.
"""

import argparse
import csv
import hashlib
import io
import re
import sys
from pathlib import Path


def rng(prefix: str, first: int, last: int) -> list[str]:
    return [f"SRS-{prefix}-{i:03d}" for i in range(first, last + 1)]


# SQT-TN-AP I1R0, release plan: the SRS requirement groups of each release.
RELEASES: dict[str, list[str]] = {
    "SW-0": rng("FUNC", 1, 4) + rng("FUNC", 7, 9) + rng("FUNC", 18, 20)
    + rng("IF", 1, 3) + rng("IF", 6, 8) + rng("QUAL", 1, 3) + rng("CDR", 1, 3)
    + rng("DES", 1, 5) + rng("GEN", 1, 2) + rng("PORT", 1, 2) + ["SRS-INST-001"],
    "SW-1": rng("FUNC", 5, 6) + rng("FUNC", 10, 15) + rng("FUNC", 21, 23)
    + rng("PERF", 1, 4) + rng("REL", 1, 4) + rng("OPS", 1, 8) + rng("HF", 1, 2)
    + rng("DATA", 1, 3) + rng("RES", 1, 3) + rng("MAINT", 1, 2),
    "SW-2": rng("FUNC", 16, 17) + ["SRS-CDR-004"] + rng("VAL", 1, 2),
}

UID = re.compile(r"^SRS-[A-Z]+-\d{3}$")
# A StrictDoc node marker on a line of its own, e.g. [TEXT] or [[/SECTION]].
# Text inside a node can start a line with "[LINK: ...]", which is no marker.
MARKER = re.compile(r"\n\[\[?/?[A-Z_]+\]\]?\n")


def read_srs(text: str) -> list[dict]:
    """Requirements of the SRS in document order, without deleted ones."""
    reqs = []
    for block in re.split(r"\n\[(?:REQUIREMENT|COMPOSITE_REQUIREMENT)\]\n", text)[1:]:
        block = MARKER.split(block)[0]
        uid = re.search(r"^UID: (\S+)", block, re.M)
        if not uid or not UID.match(uid.group(1)):
            continue
        title = re.search(r"^TITLE: (.*)", block, re.M)
        title = title.group(1).strip() if title else ""
        if title.startswith("Deleted:"):
            continue
        method = re.search(r"^VERIFICATION_METHOD: (.*)", block, re.M)
        reqs.append({
            "uid": uid.group(1),
            "title": title,
            "method": method.group(1).strip() if method else "",
        })
    return reqs


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--srs", type=Path, required=True, help="the SRS StrictDoc file")
    ap.add_argument("--source", required=True, help='where the SRS came from, e.g. "pdr (bfe0c5d)"')
    ap.add_argument("--out", type=Path, default=Path("ci/requirements.csv"))
    args = ap.parse_args()

    raw = args.srs.read_bytes()
    reqs = read_srs(raw.decode())
    known = {r["uid"] for r in reqs}
    release_of = {}
    for release, uids in RELEASES.items():
        for uid in uids:
            if uid not in known:
                print(f"error: {uid} of {release} is not in the SRS", file=sys.stderr)
                return 1
            if uid in release_of:
                print(f"error: {uid} is in {release_of[uid]} and {release}", file=sys.stderr)
                return 1
            release_of[uid] = release

    buf = io.StringIO()
    buf.write("# SPDX-FileCopyrightText: 2026 Ateleris GmbH\n")
    buf.write("# SPDX-License-Identifier: ESA-PL-permissive-2.4\n")
    buf.write("# SRS requirements for ci/fulfilment-matrix.py. Generated by\n")
    buf.write("# ci/requirements-from-srs.py; do not edit by hand.\n")
    buf.write(f"# SRS SQT-SP-0001-ATS from the documentation repository at {args.source},\n")
    buf.write(f"# SHA-256 {hashlib.sha256(raw).hexdigest()}.\n")
    buf.write("# release: the release planned for the requirement in SQT-TN-AP; empty if none.\n")
    writer = csv.writer(buf, lineterminator="\n")
    writer.writerow(["uid", "title", "method", "release"])
    for r in reqs:
        writer.writerow([r["uid"], r["title"], r["method"], release_of.get(r["uid"], "")])
    args.out.write_text(buf.getvalue())

    unplanned = [r["uid"] for r in reqs if r["uid"] not in release_of]
    print(f"{len(reqs)} requirements written to {args.out}; in no release: {', '.join(unplanned) or 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
